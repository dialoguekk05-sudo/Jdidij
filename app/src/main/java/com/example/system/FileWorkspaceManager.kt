package com.example.system

import android.content.Context
import android.content.Intent
import android.net.Uri
import android.provider.OpenableColumns
import androidx.core.content.FileProvider
import com.example.data.local.GeneratedProjectEntity
import com.example.data.local.ProjectFileEntity
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import org.xmlpull.v1.XmlPullParser
import org.xmlpull.v1.XmlPullParserFactory
import java.io.File
import java.io.FileOutputStream
import java.io.StringReader
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream

data class ImportedExternalFile(
    val displayName: String,
    val content: String,
    val sizeBytes: Long
)

data class ValidationIssue(
    val filePath: String,
    val message: String
)

class FileWorkspaceManager(private val context: Context) {

    private val projectsRoot: File
        get() = File(context.filesDir, "jarvis_projects").apply { mkdirs() }

    private val exportsRoot: File
        get() = File(context.cacheDir, "jarvis_exports").apply { mkdirs() }

    suspend fun syncProjectToDisk(
        project: GeneratedProjectEntity,
        files: List<ProjectFileEntity>
    ): File = withContext(Dispatchers.IO) {
        val safeFolder = project.name.lowercase()
            .replace(Regex("[^a-z0-9_]+"), "_")
            .trim('_')
            .ifBlank { "project_${project.id}" }
        val projectDir = File(projectsRoot, "${project.id}_$safeFolder").apply {
            if (exists()) deleteRecursively()
            mkdirs()
        }
        files.forEach { fileEntity ->
            val sanitizedPath = fileEntity.relativePath.trimStart('/', '.')
            if (!sanitizedPath.contains("..")) {
                val target = File(projectDir, sanitizedPath)
                target.parentFile?.mkdirs()
                target.writeText(fileEntity.content)
            }
        }
        projectDir
    }

    suspend fun exportProjectAsZipToUri(
        project: GeneratedProjectEntity,
        files: List<ProjectFileEntity>,
        destinationUri: Uri
    ): Result<Int> = withContext(Dispatchers.IO) {
        runCatching {
            val allEntries = buildExportFileMap(project, files)
            context.contentResolver.openOutputStream(destinationUri)?.use { outStream ->
                ZipOutputStream(outStream).use { zip ->
                    allEntries.forEach { (path, content) ->
                        zip.putNextEntry(ZipEntry(path))
                        zip.write(content.toByteArray(Charsets.UTF_8))
                        zip.closeEntry()
                    }
                }
            } ?: error("Unable to open destination file stream.")
            allEntries.size
        }
    }

    suspend fun createShareableZipIntent(
        project: GeneratedProjectEntity,
        files: List<ProjectFileEntity>
    ): Result<Intent> = withContext(Dispatchers.IO) {
        runCatching {
            val safeName = project.name.lowercase()
                .replace(Regex("[^a-z0-9_]+"), "_")
                .trim('_')
                .ifBlank { "jarvis_project" }
            val zipFile = File(exportsRoot, "${safeName}_bundle.zip")
            val allEntries = buildExportFileMap(project, files)
            ZipOutputStream(FileOutputStream(zipFile)).use { zip ->
                allEntries.forEach { (path, content) ->
                    zip.putNextEntry(ZipEntry(path))
                    zip.write(content.toByteArray(Charsets.UTF_8))
                    zip.closeEntry()
                }
            }
            val uri = FileProvider.getUriForFile(
                context,
                "${context.packageName}.fileprovider",
                zipFile
            )
            Intent(Intent.ACTION_SEND).apply {
                type = "application/zip"
                putExtra(Intent.EXTRA_STREAM, uri)
                putExtra(Intent.EXTRA_SUBJECT, "${project.name} - Generated by JARVIS AI")
                addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
            }
        }
    }

    suspend fun readExternalTextFile(uri: Uri): Result<ImportedExternalFile> =
        withContext(Dispatchers.IO) {
            runCatching {
                val maxBytes = 512 * 1024 // 512 KB cap for limited RAM safety
                val displayName = resolveDisplayName(uri) ?: "imported_file.txt"
                val bytes = context.contentResolver.openInputStream(uri)?.use { input ->
                    val buffer = input.readNBytes(maxBytes + 1)
                    if (buffer.size > maxBytes) {
                        error("File exceeds 512 KB safe limit for low-RAM editing.")
                    }
                    buffer
                } ?: error("Cannot read selected file.")
                ImportedExternalFile(
                    displayName = displayName,
                    content = bytes.toString(Charsets.UTF_8),
                    sizeBytes = bytes.size.toLong()
                )
            }
        }

    suspend fun writeTextToExternalUri(uri: Uri, content: String): Result<Unit> =
        withContext(Dispatchers.IO) {
            runCatching {
                context.contentResolver.openOutputStream(uri, "wt")?.use { out ->
                    out.write(content.toByteArray(Charsets.UTF_8))
                } ?: error("Could not open target URI for writing.")
            }
        }

    fun validateProjectFiles(files: List<ProjectFileEntity>): List<ValidationIssue> {
        val issues = mutableListOf<ValidationIssue>()
        files.forEach { file ->
            val path = file.relativePath
            val content = file.content
            if (content.isBlank()) {
                issues.add(ValidationIssue(path, "File is empty."))
                return@forEach
            }
            when {
                path.endsWith(".xml", ignoreCase = true) -> {
                    validateXml(path, content)?.let { issues.add(it) }
                }
                path.endsWith(".kt", ignoreCase = true) ||
                    path.endsWith(".java", ignoreCase = true) ||
                    path.endsWith(".js", ignoreCase = true) ||
                    path.endsWith(".css", ignoreCase = true) -> {
                    validateBalancedDelimiters(path, content)?.let { issues.add(it) }
                }
                path.endsWith(".html", ignoreCase = true) -> {
                    if (!content.contains("<html", ignoreCase = true)) {
                        issues.add(ValidationIssue(path, "Missing <html> root tag."))
                    }
                }
            }
        }
        return issues
    }

    private fun validateXml(path: String, xml: String): ValidationIssue? {
        return try {
            val factory = XmlPullParserFactory.newInstance()
            val parser = factory.newPullParser()
            parser.setInput(StringReader(xml))
            while (parser.next() != XmlPullParser.END_DOCUMENT) {
                // Parse entire XML tree to catch malformed tags
            }
            null
        } catch (e: Exception) {
            ValidationIssue(path, "XML syntax error: ${e.message ?: "Malformed XML"}")
        }
    }

    private fun validateBalancedDelimiters(path: String, code: String): ValidationIssue? {
        var braces = 0
        var parens = 0
        var inSingleQuote = false
        var inDoubleQuote = false
        var escaped = false

        for (ch in code) {
            if (escaped) {
                escaped = false
                continue
            }
            if (ch == '\\') {
                escaped = true
                continue
            }
            if (ch == '"' && !inSingleQuote) {
                inDoubleQuote = !inDoubleQuote
                continue
            }
            if (ch == '\'' && !inDoubleQuote) {
                inSingleQuote = !inSingleQuote
                continue
            }
            if (inSingleQuote || inDoubleQuote) continue

            when (ch) {
                '{' -> braces++
                '}' -> braces--
                '(' -> parens++
                ')' -> parens--
            }
            if (braces < 0) return ValidationIssue(path, "Unmatched closing '}' brace detected.")
            if (parens < 0) return ValidationIssue(path, "Unmatched closing ')' parenthesis detected.")
        }
        if (braces != 0) return ValidationIssue(path, "Unclosed '{' brace ($braces remaining).")
        if (parens != 0) return ValidationIssue(path, "Unclosed '(' parenthesis ($parens remaining).")
        return null
    }

    private fun buildExportFileMap(
        project: GeneratedProjectEntity,
        files: List<ProjectFileEntity>
    ): Map<String, String> {
        val map = linkedMapOf<String, String>()
        files.forEach { file ->
            map[file.relativePath.trimStart('/')] = file.content
        }
        if (project.projectType == "ANDROID_KOTLIN") {
            map.putIfAbsent(
                "build_debug_apk.sh",
                """#!/usr/bin/env bash
set -e
echo "Building Debug APK for ${project.name}..."
./gradlew assembleDebug
echo "Debug APK generated at: app/build/outputs/apk/debug/app-debug.apk"
""".trimIndent()
            )
            map.putIfAbsent(
                ".github/workflows/build_apk.yml",
                """name: Build Debug APK
on: [workflow_dispatch, push]
jobs:
  build:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-java@v4
        with:
          distribution: temurin
          java-version: 17
      - name: Build Debug APK
        run: ./gradlew assembleDebug
      - uses: actions/upload-artifact@v4
        with:
          name: app-debug-apk
          path: app/build/outputs/apk/debug/app-debug.apk
""".trimIndent()
            )
        }
        return map
    }

    private fun resolveDisplayName(uri: Uri): String? {
        return context.contentResolver.query(uri, null, null, null, null)?.use { cursor ->
            val idx = cursor.getColumnIndex(OpenableColumns.DISPLAY_NAME)
            if (idx >= 0 && cursor.moveToFirst()) cursor.getString(idx) else null
        }
    }
}
